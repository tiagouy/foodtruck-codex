import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const gradle = read('apps/mobile/android/app/build.gradle');
assert.match(gradle, /applicationId "org\.useful_media_app\.foodtruck"/);
assert.match(gradle, /applicationIdSuffix "\.dev"/);
assert.match(gradle, /namespace "com\.foodtrucksuy\.dev"/);
assert.match(gradle, /FTUY_ANDROID_VERSION_CODE/);
assert.match(gradle, /FTUY_STORE_VERSION/);
assert.match(gradle, /storeCode\.toInteger\(\) <= 40200/);
const release = gradle.slice(gradle.indexOf('        release {'));
assert.doesNotMatch(release, /signingConfig signingConfigs\.debug/);
const ios = read('apps/mobile/ios/FoodtrucksUY.xcodeproj/project.pbxproj');
assert.match(ios, /PRODUCT_BUNDLE_IDENTIFIER = com\.foodtrucksuy\.dev/);
assert.doesNotMatch(ios, /PRODUCT_BUNDLE_IDENTIFIER = org\.useful_media_app/);
const pkg = JSON.parse(read('apps/mobile/package.json'));
const lock = JSON.parse(read('apps/mobile/package-lock.json'));
assert.match(pkg.version, /^\d+\.\d+\.\d+$/); assert.equal(lock.version, pkg.version);
assert.equal(lock.packages[''].version, pkg.version);
console.log('12 identity/configuration checks passed; iOS store identity deliberately unconfirmed.');
